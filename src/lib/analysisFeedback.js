// رسائل آمنة للمستخدم بعد حفظ المستند؛ لا نعرض أخطاء المزوّد أو نص الفاتورة.
// انتهاء مهلة القراءة: المستند محفوظ بصفحاته كاملة، ويُقرأ من جديد من «مستندات جديدة» دون رفع نسخة أخرى.
export function savedDocumentWarning(error) {
  if (error?.isReadingTimeout) {
    return `حُفظ المستند للمراجعة — ${error.message} تُعاد قراءته من «مستندات جديدة» بزر «قراءة المستند»؛ لا حاجة لرفعه مرة أخرى.`
  }
  const reason = error?.isAuthError
    ? error.message
    : 'تعذّر إكمال التحليل التلقائي.'
  return `حُفظ المستند للمراجعة — ${reason} لا حاجة لرفعه مرة أخرى.`
}
