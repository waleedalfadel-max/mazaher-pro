// قراءة مبالغ «سجل الدفتر» من حقول نصية (src/ui/format.js parseAmount): الصيغ الصحيحة تُقبل، والفارغ صفر، وما سواها يُرفض (NaN) لا يصير صفرًا.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { parseAmount } from '../src/ui/format.js'

test('الصيغ الصحيحة: لاتينية وعربية وفارسية، وفاصلة عشرية، وفواصل آلاف في مواضعها، والسالب كما كان', () => {
  for (const [v, want] of [['270', 270], ['15.5', 15.5], [' 40 ', 40], ['0', 0], ['0.75', 0.75], ['.5', 0.5], ['5.', 5], ['-5', -5], ['−5', -5],
    ['1,000', 1000], ['1,000.25', 1000.25], ['12,345,678.9', 12345678.9], ['٢٧٠', 270], ['١٥٫٥', 15.5], ['١٬٢٣٠٫٥', 1230.5], ['۱۲', 12],
    [270, 270], [15.5, 15.5], ['-0', 0]]) {
    assert.equal(parseAmount(v), want, String(v))
  }
})

test('الفارغ صفر (الحقل اختياري)', () => {
  for (const v of ['', '   ', null, undefined]) assert.equal(parseAmount(v), 0, String(v))
})

test('المدخل غير الصالح يُرفض (NaN) بدل الصفر الصامت أو رقم آخر', () => {
  for (const v of ['230 ريال', 'ريال 230', 'abc', '12.3.4', '1,23', '1,2345', ',100', '100,', '1 000', '1e3', '0x10', 'Infinity', '-', '.', '--5', '5-', '+5', '٢٣٠ ر.س', NaN, Infinity]) {
    assert.ok(Number.isNaN(parseAmount(v)), String(v))
  }
})
